from fastapi import APIRouter, BackgroundTasks
from app.core.schema_manager import schema_manager

router = APIRouter(prefix="/api/schema", tags=["schema"])


@router.get("/version")
async def get_schema_version():
    info = schema_manager.get_version_info()
    return info or {"version": "not_loaded", "updated_at": None}


# Shown when the schema file has no description for a category
CATEGORY_DESCRIPTIONS = {
    1: "Events generated by the operating system",
    2: "Security findings such as alerts and vulnerabilities",
    3: "Authentication and authorization events",
    4: "Network traffic and connection events",
    5: "Asset and configuration discovery events",
    6: "Application-level events",
    7: "Remediation actions taken against threats",
    8: "Unmanned and airborne systems activity",
}


@router.get("/classes")
async def get_ocsf_classes():
    return [
        {
            "uid": c.get("uid"),
            "name": c.get("name"),
            "caption": c.get("caption"),
            "description": (c.get("description") or "")[:200],
            "category_uid": c.get("category_uid"),
            "category": c.get("category_name") or c.get("category"),
            "deprecated": bool(c.get("@deprecated")),
        }
        for c in sorted(schema_manager._iter_classes(), key=lambda c: c.get("uid") or 0)
        if c.get("uid")
    ]


@router.get("/categories")
async def get_ocsf_categories():
    """Categories present in the loaded schema, so new OCSF releases show up without a code change."""
    found: dict[int, str] = {}
    for c in schema_manager._iter_classes():
        uid = c.get("category_uid")
        if isinstance(uid, int) and uid > 0:
            found.setdefault(uid, c.get("category_name") or f"Category {uid}")
    if not found:
        found = {1: "System Activity", 2: "Findings", 3: "Identity & Access Management",
                 4: "Network Activity", 5: "Discovery", 6: "Application Activity"}
    return [{"uid": uid, "name": name, "description": CATEGORY_DESCRIPTIONS.get(uid, "")}
            for uid, name in sorted(found.items())]


@router.post("/update")
async def trigger_schema_update(force: bool = False, background_tasks: BackgroundTasks = None):
    result = await schema_manager.update_schema(force=force)
    return result


@router.get("/fields/{class_uid}")
async def get_class_fields(class_uid: int):
    fields = await schema_manager.get_class_attributes(class_uid)
    return {"class_uid": class_uid, "fields": fields}


@router.post("/validate")
async def validate_event(event: dict):
    is_valid, errors = schema_manager.validate_event(event)
    return {"valid": is_valid, "errors": errors}
