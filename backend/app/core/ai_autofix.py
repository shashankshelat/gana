"""AI mapping proposals for a connector, from failed (DLQ) events or analyst-provided samples.

One entry point (`propose`) serves the automatic scheduler job, the "Generate now" button, the
"Ask AI to fix" action on the DLQ page, and pasted samples. Every proposal is a pending approval
for an analyst; nothing reaches the live mapping without review."""
import json
import logging
import uuid
from datetime import datetime, timedelta, timezone

from sqlalchemy import select

from app.core.database import AsyncSessionLocal

logger = logging.getLogger(__name__)

SOURCE_AUTO = "dlq_auto"      # generated by the scheduler from new DLQ events
SOURCE_MANUAL = "dlq_ai"      # analyst asked for it (connector page or DLQ page)
SOURCE_SAMPLES = "samples_ai"  # analyst pasted sample events
AI_SOURCES = (SOURCE_AUTO, SOURCE_MANUAL, SOURCE_SAMPLES, "auto_ai", "ai")


async def get_settings(db, connector_id: str):
    from app.models.connector_ai import ConnectorAISettingsModel
    row = await db.get(ConnectorAISettingsModel, connector_id)
    if row is None:
        row = ConnectorAISettingsModel(connector_id=connector_id, auto_enabled=True, min_events=1,
                                       cooldown_minutes=60, daily_limit=10, max_samples=10, runs_today=0)
        db.add(row)
        await db.flush()
    return row


async def pending_proposal(db, connector_id: str):
    from app.models.approval import MappingApprovalModel
    return (await db.execute(
        select(MappingApprovalModel).where(
            MappingApprovalModel.connector_id == connector_id,
            MappingApprovalModel.status == "pending",
            MappingApprovalModel.source.in_(AI_SOURCES),
        ).order_by(MappingApprovalModel.created_at.desc()).limit(1)
    )).scalars().first()


async def unlinked_failed_events(db, connector_id: str) -> list:
    """Pending DLQ events for the connector that no pending proposal already covers."""
    from app.models.approval import ApprovalDLQLinkModel, MappingApprovalModel
    from app.models.dlq import DLQEventModel
    covered: set[str] = set()
    links = (await db.execute(
        select(ApprovalDLQLinkModel).join(MappingApprovalModel, MappingApprovalModel.id == ApprovalDLQLinkModel.approval_id)
        .where(MappingApprovalModel.connector_id == connector_id, MappingApprovalModel.status == "pending")
    )).scalars().all()
    for link in links:
        covered.update(link.dlq_event_ids or [])
    events = (await db.execute(
        select(DLQEventModel).where(DLQEventModel.connector_id == connector_id, DLQEventModel.discarded == False)  # noqa: E712
        .order_by(DLQEventModel.created_at.desc())
    )).scalars().all()
    return [e for e in events if e.id not in covered]


async def ai_provider_config() -> tuple[str, str, str]:
    from app.api.settings import get_setting_value
    from app.core.ai_mapper import AI_PROVIDERS
    provider = await get_setting_value("ai.default_provider", "claude")
    key = await get_setting_value(f"ai.{provider}_api_key", "")
    model = AI_PROVIDERS.get(provider, {}).get("default_model", "")
    return provider, model, key


async def propose(connector_id: str, *, source: str, created_by: str,
                  dlq_ids: list[str] | None = None, samples: list[dict] | None = None) -> dict:
    """Generate a mapping proposal and file it as a pending approval.

    dlq_ids=None with no samples means "all failed events not yet covered by a pending proposal"."""
    from app.core.ai_mapper import generate_mapping_fix
    from app.models.approval import ApprovalDLQLinkModel, MappingApprovalModel, UnknownFieldModel
    from app.models.connector import ConnectorModel
    from app.models.dlq import DLQEventModel

    provider, model, key = await ai_provider_config()
    if not key:
        return {"status": "skipped", "message": "No AI API key configured (Settings → AI Providers)"}

    async with AsyncSessionLocal() as db:
        connector = await db.get(ConnectorModel, connector_id)
        if not connector:
            return {"status": "error", "message": "Connector no longer exists"}
        ai = await get_settings(db, connector_id)

        if samples is not None:
            events, raws, errors, reason = [], samples[: ai.max_samples], [], "samples"
        else:
            if dlq_ids is not None:
                events = (await db.execute(select(DLQEventModel).where(
                    DLQEventModel.id.in_(dlq_ids), DLQEventModel.connector_id == connector_id,
                    DLQEventModel.discarded == False))).scalars().all()  # noqa: E712
            else:
                events = await unlinked_failed_events(db, connector_id)
            if not events:
                return {"status": "skipped", "message": "No failed events to learn from"}
            sample_events = events[: ai.max_samples]
            raws = [(e.raw_event or {}).get("_raw_data", e.raw_event) for e in sample_events]
            errors = [f"{e.error_type}: {e.error_message}" for e in sample_events]
            reason = "failed"
        class_uid = 3002 if connector.ocsf_class_uid is None else connector.ocsf_class_uid
        current = connector.mapping_rules or {}
        await db.commit()

    try:
        result = await generate_mapping_fix(
            failed_events=raws, errors=errors, current_mapping=current, connector_type=connector.connector_type,
            ocsf_class_uid=class_uid, provider=provider, model=model, api_key=key, reason=reason,
        )
    except Exception as e:
        logger.error("AI mapping proposal failed for connector %s: %s", connector_id, e)
        return {"status": "error", "message": f"{type(e).__name__}: {str(e)[:300]}"}

    async with AsyncSessionLocal() as db:
        approval = MappingApprovalModel(
            id=str(uuid.uuid4()), connector_id=connector_id, connector_type=connector.connector_type,
            connector_name=connector.name, ocsf_class_uid=class_uid, source=source,
            ai_provider=provider, ai_model=model,
            sample_logs=json.dumps(raws[:5], indent=2, default=str)[:5000],
            proposed_mapping=result["mapping"], current_mapping=current,
            ai_explanation=result.get("explanation", ""), status="pending", created_by=created_by,
        )
        db.add(approval)
        if events:
            # Link every failed event this proposal covers, not only the samples, so approval replays them all
            db.add(ApprovalDLQLinkModel(approval_id=approval.id, dlq_event_ids=[e.id for e in events]))
        for uf in result.get("unknown_fields", []):
            db.add(UnknownFieldModel(
                id=str(uuid.uuid4()), approval_id=approval.id, connector_type=connector.connector_type,
                field_name=uf.get("field_name", "unknown"), field_path=uf.get("field_path", ""),
                sample_values=uf.get("sample_values", []), ai_description=uf.get("description", ""),
                ai_suggested_ocsf_path=uf.get("suggested_ocsf_path", ""), status="pending",
            ))
        await db.commit()

    routes = len(result["mapping"].get("_routes") or [])
    return {"status": "proposed", "approval_id": approval.id, "events": len(events),
            "rules_proposed": len([k for k in result["mapping"] if not k.startswith("_")]), "routes_proposed": routes,
            "message": f"Proposal ready for review ({routes} routes, from {len(events) or len(raws)} events)"}


async def _record(connector_id: str, status: str, message: str, ran: bool) -> None:
    async with AsyncSessionLocal() as db:
        ai = await get_settings(db, connector_id)
        ai.last_status, ai.last_message = status, message[:1000]
        if ran:
            today = datetime.now(timezone.utc).strftime("%Y-%m-%d")
            ai.runs_today = (ai.runs_today or 0) + 1 if ai.runs_day == today else 1
            ai.runs_day = today
            ai.last_run_at = datetime.utcnow()
        await db.commit()


async def run_automatic() -> None:
    """Scheduler job: propose mappings for connectors with new failed events, within each one's guardrails."""
    from app.core.poller import _get_redis
    from app.models.connector import ConnectorModel

    _, _, key = await ai_provider_config()
    if not key:
        return
    async with AsyncSessionLocal() as db:
        connectors = (await db.execute(select(ConnectorModel).where(ConnectorModel.enabled == True))).scalars().all()  # noqa: E712
        ids = [c.id for c in connectors]

    for cid in ids:
        # All uvicorn workers run this job; one lock per connector keeps it to a single proposal
        try:
            if not await (await _get_redis()).set(f"ocsf:ai-auto:{cid}", "1", nx=True, ex=240):
                continue
        except Exception as e:
            logger.error("Redis unavailable; skipping automatic AI mapping: %s", e)
            return

        async with AsyncSessionLocal() as db:
            ai = await get_settings(db, cid)
            settings_snapshot = (ai.auto_enabled, ai.min_events, ai.cooldown_minutes, ai.daily_limit,
                                 ai.last_run_at, ai.runs_day, ai.runs_today)
            waiting = await pending_proposal(db, cid)
            failed = len(await unlinked_failed_events(db, cid))
            await db.commit()
        enabled, min_events, cooldown, limit, last_run, runs_day, runs_today = settings_snapshot
        if not enabled or failed < max(1, min_events):
            continue
        if waiting:
            await _record(cid, "waiting_review", "A proposal is waiting for review in Approvals", ran=False)
            continue
        if last_run and datetime.utcnow() - last_run < timedelta(minutes=cooldown):
            continue
        today = datetime.now(timezone.utc).strftime("%Y-%m-%d")
        if runs_day == today and (runs_today or 0) >= limit:
            await _record(cid, "skipped", f"Daily limit of {limit} automatic runs reached", ran=False)
            continue

        result = await propose(cid, source=SOURCE_AUTO, created_by="gana-auto")
        await _record(cid, result["status"], result["message"], ran=result["status"] in ("proposed", "error"))
        if result["status"] == "proposed":
            logger.info("Automatic AI mapping proposal %s for connector %s", result["approval_id"], cid)
